CREATE TABLE IF NOT EXISTS lessons (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  "text" text NOT NULL,
  source_type text NOT NULL,
  youtube_id text,
  audio_url text,
  cues_json text,
  created_at bigint NOT NULL,
  last_opened_at bigint,
  "position" bigint DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_lessons_last_opened ON lessons (last_opened_at DESC NULLS LAST, created_at DESC);

CREATE TABLE IF NOT EXISTS words (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lemma text UNIQUE NOT NULL,
  surface text NOT NULL,
  translation text,
  grammar text,
  status integer DEFAULT 1 NOT NULL,
  ease real DEFAULT 2.5 NOT NULL,
  interval_days integer DEFAULT 0 NOT NULL,
  reps integer DEFAULT 0 NOT NULL,
  lapses integer DEFAULT 0 NOT NULL,
  due_at bigint,
  created_at bigint NOT NULL,
  updated_at bigint,
  last_reviewed_at bigint
);

CREATE INDEX IF NOT EXISTS idx_words_status ON words (status);
CREATE INDEX IF NOT EXISTS idx_words_due ON words (due_at ASC NULLS FIRST, lemma ASC);

CREATE TABLE IF NOT EXISTS contexts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  word_id bigint NOT NULL REFERENCES words(id) ON DELETE CASCADE,
  lesson_id bigint REFERENCES lessons(id) ON DELETE SET NULL,
  sentence text NOT NULL,
  created_at bigint NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_contexts_word ON contexts (word_id, created_at DESC);

CREATE TABLE IF NOT EXISTS reviews (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  word_id bigint NOT NULL REFERENCES words(id) ON DELETE CASCADE,
  grade integer NOT NULL,
  interval_before integer NOT NULL,
  interval_after integer NOT NULL,
  reviewed_at bigint NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_reviews_word ON reviews (word_id, reviewed_at DESC);
CREATE INDEX IF NOT EXISTS idx_reviews_time ON reviews (reviewed_at DESC);

CREATE TABLE IF NOT EXISTS translations (
  source text NOT NULL,
  target_lang text NOT NULL,
  result text NOT NULL,
  created_at bigint NOT NULL,
  PRIMARY KEY (source, target_lang)
);

CREATE TABLE IF NOT EXISTS dictionary_cache (
  lemma text PRIMARY KEY,
  payload text NOT NULL,
  created_at bigint NOT NULL
);

