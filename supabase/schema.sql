create table if not exists lessons (
    id bigint generated by default as identity primary key,
    title text not null,
    "text" text not null,
    source_type text not null default 'text',
    youtube_id text,
    audio_url text,
    cues_json text,
    created_at bigint not null,
    last_opened_at bigint,
    "position" bigint not null default 0
);

create table if not exists words (
    id bigint generated by default as identity primary key,
    lemma text not null unique,
    surface text,
    translation text,
    grammar text,
    status integer not null default 1,
    ease double precision not null default 2.5,
    interval_days bigint not null default 0,
    reps integer not null default 0,
    lapses integer not null default 0,
    due_at bigint,
    created_at bigint not null,
    updated_at bigint not null,
    last_reviewed_at bigint
);

create table if not exists contexts (
    id bigint generated by default as identity primary key,
    word_id bigint not null references words (id) on delete cascade,
    lesson_id bigint references lessons (id) on delete set null,
    sentence text not null,
    created_at bigint not null
);

create table if not exists translations (
    id bigint generated by default as identity primary key,
    source text not null,
    target_lang text not null default 'en',
    result text not null,
    created_at bigint not null,
    unique (source, target_lang)
);

create table if not exists dictionary_cache (
    id bigint generated by default as identity primary key,
    lemma text not null unique,
    payload text not null,
    created_at bigint not null
);

create table if not exists reviews (
    id bigint generated by default as identity primary key,
    word_id bigint references words (id) on delete set null,
    grade integer not null,
    interval_before double precision not null default 0,
    interval_after double precision not null default 0,
    reviewed_at bigint not null
);

create index if not exists idx_words_status on words (status);
create index if not exists idx_words_due on words (due_at);
create index if not exists idx_contexts_word on contexts (word_id);
create index if not exists idx_reviews_reviewed on reviews (reviewed_at);

alter table lessons enable row level security;
alter table words enable row level security;
alter table contexts enable row level security;
alter table translations enable row level security;
alter table dictionary_cache enable row level security;
alter table reviews enable row level security;
